import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import pg from 'pg';
import {detectRelease,subscribe,changeSubscription,deliverOne,publicLatest} from './server.mjs';
const url=process.env.PUSH_TEST_DATABASE_URL;
if(!url||!['127.0.0.1','localhost'].includes(new URL(url).hostname)||new URL(url).pathname!=='/pool_alerts_test')throw Error('Disposable local test database required');
const pool=new pg.Pool({connectionString:url,max:6});
const keys={p256dh:Buffer.concat([Buffer.from([4]),Buffer.alloc(64)]).toString('base64url'),auth:Buffer.alloc(16).toString('base64url')};
const row={season:2026,week:11,revision:1,status:'locked',published_at:'2026-11-18T12:00:00.000Z'};
let visible={...row},sent=[];
const readPublic=async()=>({...visible});
const readDeliveries=async()=> (await pool.query('SELECT * FROM pool_alerts.deliveries ORDER BY week,revision,subscription_id')).rows;
const release=async x=>{await pool.query('INSERT INTO public.nfl_pool_weeks VALUES($1,$2,$3,$4,$5) ON CONFLICT(season,week) DO UPDATE SET revision=EXCLUDED.revision,status=EXCLUDED.status,published_at=EXCLUDED.published_at',[x.season,x.week,x.revision,x.status,x.published_at]);visible=x};
try{
  await pool.query('CREATE TABLE public.nfl_pool_weeks(season integer,week integer,revision integer,status text,published_at timestamptz,PRIMARY KEY(season,week))');
  await pool.query(await readFile(new URL('./schema.sql',import.meta.url),'utf8'));
  await pool.query("CREATE ROLE alerts_anon NOLOGIN");
  assert.equal((await pool.query("SELECT has_schema_privilege('alerts_anon','pool_alerts','USAGE') AS allowed")).rows[0].allowed,false);
  const a=await subscribe(pool,{endpoint:'https://fcm.googleapis.com/fcm/send/a',keys},true);
  const b=await subscribe(pool,{endpoint:'https://web.push.apple.com/b',keys},false);
  await assert.rejects(subscribe(pool,{endpoint:'https://fcm.googleapis.com/fcm/send/a',keys}));
  assert.equal(await changeSubscription(pool,a.id,b.token,{enabled:false,corrections:false}),false);
  await release(row);assert.equal(await detectRelease(pool,readPublic),'baseline');
  assert.equal((await readDeliveries()).length,0);
  const next={...row,week:12,published_at:'2026-11-25T12:00:00.000Z'};
  await release(next);
  await assert.rejects(detectRelease(pool,async()=>row));
  assert.equal((await readDeliveries()).length,0);
  assert.deepEqual((await Promise.all([detectRelease(pool,readPublic),detectRelease(pool,readPublic)])).sort(),['enqueue','ignore']);
  assert.equal((await readDeliveries()).length,2);
  const send=async(sub,payload)=>{sent.push({endpoint:sub.endpoint,payload});return {statusCode:201}};
  await Promise.all([deliverOne(pool,send),deliverOne(pool,send),deliverOne(pool,send)]);
  assert.equal(sent.length,2);assert.equal(new Set(sent.map(x=>x.endpoint)).size,2);
  assert((await readDeliveries()).every(x=>x.state==='sent'));
  const correction={...next,revision:2,published_at:'2026-11-25T13:00:00.000Z'};
  await release(correction);assert.equal(await detectRelease(pool,readPublic),'enqueue');
  assert.equal((await readDeliveries()).filter(d=>d.revision===2).length,1);
  await deliverOne(pool,async()=>{throw Object.assign(Error('rate limited'),{statusCode:429})});
  assert.equal((await readDeliveries()).find(d=>d.revision===2).state,'retry');
  await pool.query("UPDATE pool_alerts.deliveries SET next_attempt_at=now() WHERE revision=2");
  await deliverOne(pool,async()=>{throw Object.assign(Error('expired'),{statusCode:410})});
  assert.equal((await readDeliveries()).find(d=>d.revision===2).state,'expired');
  assert.equal((await pool.query('SELECT enabled FROM pool_alerts.subscriptions WHERE id=$1',[a.id])).rows[0].enabled,false);
  const later={...next,week:13,published_at:'2026-12-02T12:00:00.000Z'};
  await release(later);await detectRelease(pool,readPublic);
  assert.equal((await readDeliveries()).filter(d=>d.week===13).length,1);
  assert.equal(await changeSubscription(pool,b.id,b.token,{enabled:false,corrections:false}),true);
  assert.equal((await readDeliveries()).find(d=>d.week===13).state,'cancelled');
  assert.equal(await deliverOne(pool,send),false);
  assert.equal(sent.length,2);
  const calls=[];
  const got=await publicLatest('https://qa.neon.tech/auth','https://qa.neon.tech/rest',async(url,opts)=>{
    calls.push({url,opts});return {ok:true,json:async()=>calls.length===1?{token:'synthetic-token'}:[later]};
  });
  assert.deepEqual(got,later);assert.equal(calls[1].opts.headers.Authorization,'Bearer synthetic-token');
  console.log('Push integration passed: public readback, baseline, concurrent release deduplication, queue leases, corrections, retries, expiry and opt-out');
}finally{await pool.end()}
