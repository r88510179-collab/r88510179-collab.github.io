import assert from 'node:assert/strict';
import {identity,releaseDecision,validateSubscription,deliveryResult} from './core.mjs';
const row={season:2026,week:12,revision:1,status:'locked',published_at:'2026-11-25T15:00:00Z'};
const base=releaseDecision(null,row,row);assert.equal(base.action,'baseline');
assert.equal(releaseDecision(base.next,row,row).action,'ignore');
const newer={...row,week:13};assert.equal(releaseDecision(base.next,newer,newer).kind,'release');
const correction={...row,revision:2};assert.equal(releaseDecision(base.next,correction,correction).kind,'correction');
assert.throws(()=>releaseDecision(base.next,correction,row));
assert.throws(()=>releaseDecision(null,{...row,status:'draft'},row));
assert.throws(()=>identity({...row,week:19}));
assert.equal(releaseDecision(base.next,{...row,week:11},{...row,week:11}).action,'ignore');
const keys={p256dh:Buffer.concat([Buffer.from([4]),Buffer.alloc(64)]).toString('base64url'),auth:Buffer.alloc(16).toString('base64url')};
assert.equal(validateSubscription({endpoint:'https://fcm.googleapis.com/fcm/send/test',keys}).keys.auth,keys.auth);
for(const endpoint of ['http://fcm.googleapis.com/a','https://fcm.googleapis.com.evil.example/a','https://127.0.0.1/a','https://fcm.googleapis.com:444/a','https://fcm.googleapis.com@evil.example/a'])assert.throws(()=>validateSubscription({endpoint,keys}));
assert.throws(()=>validateSubscription({endpoint:'https://fcm.googleapis.com/a',keys:{...keys,auth:'abc'}}));
assert.deepEqual(deliveryResult(201,1),{state:'sent'});
assert.deepEqual(deliveryResult(410,1),{state:'expired'});
assert.deepEqual(deliveryResult(429,2),{state:'retry',delaySeconds:60});
assert.deepEqual(deliveryResult(503,6),{state:'failed'});
console.log('Push policy: release, correction, baseline, public verification, SSRF and delivery outcomes passed');
